#include "libft.h"
#include <stdlib.h>

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char			*result;
	int				str_len;
	unsigned int	i;

	if (!s || !f)
		return (NULL);
	str_len = 0;
	while (s[str_len])
		str_len++;
	result = malloc(sizeof(char) * (str_len + 1));
	if (!result)
		return (NULL);
	i = 0;
	while (s[i])
	{
		result[i] = f(i, s[i]);
		i++;
	}
	result[i] = '\0';
	return (result);
}
